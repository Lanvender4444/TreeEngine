def test_parent_section_own_text_can_be_the_answer(engine: TreeEngine) -> None:
    doc = engine.ingest_text(
        "# Guide\n\n## Troubleshooting\n\nCrashLoopBackOff is caused by application errors "
        "or missing configuration files.\n\n### Restart delay\n\nThe delay grows to five "
        "minutes.\n\n### Restart policy\n\nAlways is the default.\n",
        title="Guide",
    )
    res = engine.tree_search("What causes CrashLoopBackOff?", doc.id)
    assert [t.title for t in res.targets] == ["Troubleshooting"]
    assert res.own_text_target_ids == [res.targets[0].id]  # its own text, not the subtree
    assert "application errors" in res.evidence[0].content
    assert all(e.metadata["node_title"] == "Troubleshooting" for e in res.evidence)


