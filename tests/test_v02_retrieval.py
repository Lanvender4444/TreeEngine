def test_stemming_and_word_boundaries() -> None:
    assert stem("shuffle") == stem("shuffling") == "shuffl"
    assert stem("partitions") == "partition"
    assert stem("供应链") == "供应链"
    assert lexical_score(["shuffle"], "By default no shuffling occurs") == 1.0
    assert lexical_score(["groupkfold"], "StratifiedGroupKFold") == 0.0
    assert lexical_score(["groupkfold"], "GroupKFold is a variation") == 1.0
    assert lexical_score(["供应"], "芯片供应不足") == 1.0


