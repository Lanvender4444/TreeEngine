def test_migration_v1_to_v2_rebuilds_fts(tmp_path: Path) -> None:
    db = tmp_path / "v1.db"
    # a V0.1 database: FTS without porter, user_version = 1
    conn = sqlite3.connect(db)
    schema = (Path(__file__).parent.parent / "treeengine/storage/schema.sql").read_text("utf-8")
    schema = schema.replace(",\n    tokenize = 'porter unicode61'", "")
    conn.executescript(schema)
    conn.execute(
        "INSERT INTO documents VALUES ('d','markdown',NULL,'Doc',NULL,'x',NULL,'t','t','{}')"
    )
    conn.execute(
        "INSERT INTO nodes VALUES ('n','d',NULL,0,0,'Notes',NULL,NULL,'section',"
        "NULL,NULL,NULL,NULL)"
    )
    conn.execute(
        "INSERT INTO blocks VALUES ('b','d','n',0,'paragraph','no shuffling here',"
        "NULL,NULL,NULL,'{}')"
    )
    conn.execute(
        "INSERT INTO blocks_fts(rowid, block_id, document_id, title, content) "
        "SELECT rowid, id, document_id, 'Notes', content FROM blocks"
    )
    conn.execute("PRAGMA user_version = 1")
    conn.commit()
    conn.close()

    repo = SQLiteRepository(db)
    assert repo.schema_version == SCHEMA_VERSION == 2
    assert [b.id for b, _ in repo.fts_query(["shuffle"])] == ["b"]  # stemmed after rebuild
    assert repo.fts_integrity() == (1, 1)
    repo.close()


def test_pdf_running_headers_are_removed() -> None:
    pages, lines, pos = [], [], 0
    for p in range(1, 7):
        start = pos
        body = [f"Body text of page {p}, line {i}." for i in range(4)]
        for ln in ["Java 开发手册（黄山版）", *body, f"{p}/51"]:
            lines.append((pos, ln))
            pos += len(ln) + 1
        pages.append((p, start, pos - 1))
    noise = running_lines(lines, pages)
    kept = [lines[i][1] for i in range(len(lines)) if i not in noise]
    assert kept == [f"Body text of page {p}, line {i}." for p in range(1, 7) for i in range(4)]


