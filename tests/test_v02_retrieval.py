def test_table_of_contents_is_not_a_navigation_target(engine: TreeEngine) -> None:
    doc = engine.ingest_text(
        "# Book\n\n## 目录\n\n第一章 缓存设计\n第二章 线程池\n\n"
        "## 第一章 缓存设计\n\n缓存要设置过期时间。\n\n"
        "## 第二章 线程池\n\n线程池不允许使用 Executors 创建。\n",
        title="Book",
    )
    toc = next(n for n in engine.repo.get_document_nodes(doc.id) if n.title == "目录")
    assert toc.node_type == "toc"
    res = engine.tree_search("线程池怎么创建", doc.id)
    assert "目录" not in [t.title for t in res.targets]
    assert res.targets[0].title == "第二章 线程池"
